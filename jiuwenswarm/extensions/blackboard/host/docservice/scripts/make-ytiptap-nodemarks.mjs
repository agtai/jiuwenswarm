// Writes vendor/y-tiptap-nodemarks.js: a copy of @tiptap/y-tiptap 3.0.9 that syncs node marks.
// y-prosemirror and y-tiptap only sync marks on text; marks on block nodes (which
// prosemirror-suggest-changes uses for whole-block insertions and deletions) are dropped.
// Each node mark is stored as an element attribute `_mark_<name>` holding the mark attrs, the
// approach reviewed on y-prosemirror PR #135. Drop this once y-prosemirror PR #157 ships in y-tiptap.
//
// node <this file>          rewrite the vendored file
// node <this file> --check  exit 1 if it differs from a fresh patch
// The pinned @tiptap/y-tiptap comes from the web app's node_modules.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkgDir = join(here, '..', '..', '..', '..', '..', 'channels', 'web', 'frontend', 'node_modules', '@tiptap', 'y-tiptap')
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version
if (version !== '3.0.9') throw new Error(`the patch targets @tiptap/y-tiptap 3.0.9, found ${version}`)
let s = readFileSync(join(pkgDir, 'dist', 'y-tiptap.js'), 'utf8')

function rep(oldText, newText) {
  const n = s.split(oldText).length - 1
  if (n !== 1) throw new Error(`expected one match, found ${n}: ${oldText.slice(0, 80)}`)
  s = s.replace(oldText, newText)
}

rep(
  "import { ReplaceStep } from 'prosemirror-transform';\n",
  `import { ReplaceStep } from 'prosemirror-transform';

// ---- node marks patch (Blackboard) ----
const NODE_MARK_PREFIX = '_mark_';
const nodeMarksToAttributes = (marks) => {
  const attrs = {};
  marks.forEach((mark) => {
    // ProseMirror attrs have a null prototype, which Y.XmlElement.setAttribute rejects.
    if (mark.type.name !== 'ychange') attrs[NODE_MARK_PREFIX + mark.type.name] = Object.assign({}, mark.attrs);
  });
  return attrs
};
const pNodeAttrsWithMarks = (pnode) =>
  pnode.marks && pnode.marks.length ? Object.assign({}, pnode.attrs, nodeMarksToAttributes(pnode.marks)) : pnode.attrs;
const takeNodeMarks = (attrs, schema) => {
  const marks = [];
  for (const key of Object.keys(attrs)) {
    if (key.startsWith(NODE_MARK_PREFIX)) {
      const type = schema.marks[key.slice(NODE_MARK_PREFIX.length)];
      if (type && attrs[key] !== null && attrs[key] !== undefined) marks.push(type.create(attrs[key]));
      delete attrs[key];
    }
  }
  return marks
};
// ---- end node marks patch ----
`
)

// Y element to ProseMirror node: attributes with the prefix become node marks.
rep(
  'const node = schema.node(el.nodeName, attrs, children);',
  'const nodeMarks = takeNodeMarks(attrs, schema);\n    const node = schema.node(el.nodeName, attrs, children, nodeMarks);'
)

// ProseMirror node to new Y element: write the node marks as attributes.
rep(
  `  const type = new Y.XmlElement(node.type.name);
  for (const key in node.attrs) {
    const val = node.attrs[key];
    if (val !== null && key !== 'ychange') {
      type.setAttribute(key, val);
    }
  }`,
  `  const type = new Y.XmlElement(node.type.name);
  const nodeAttrs = pNodeAttrsWithMarks(node);
  for (const key in nodeAttrs) {
    const val = nodeAttrs[key];
    if (val !== null && key !== 'ychange') {
      type.setAttribute(key, val);
    }
  }`
)

// Equality: a node whose marks changed is not equal to its Y element.
rep(
  'equalAttrs(ytype.getAttributes(), pnode.attrs) &&',
  'equalAttrs(ytype.getAttributes(), pNodeAttrsWithMarks(pnode)) &&'
)

// Updating an existing Y element: sync the mark attributes too, and do not rewrite equal objects.
rep(
  `    const yDomAttrs = yDomFragment.getAttributes();
    const pAttrs = pNode.attrs;
    for (const key in pAttrs) {
      if (pAttrs[key] !== null) {
        if (yDomAttrs[key] !== pAttrs[key] && key !== 'ychange') {`,
  `    const yDomAttrs = yDomFragment.getAttributes();
    const pAttrs = pNodeAttrsWithMarks(pNode);
    for (const key in pAttrs) {
      if (pAttrs[key] !== null) {
        const same = yDomAttrs[key] === pAttrs[key] ||
          (isObject(yDomAttrs[key]) && isObject(pAttrs[key]) && equalAttrs(yDomAttrs[key], pAttrs[key]));
        if (!same && key !== 'ychange') {`
)

const header = `// @tiptap/y-tiptap ${version} (MIT, https://github.com/ueberdosis/y-tiptap), patched to sync node
// marks. Generated by scripts/make-ytiptap-nodemarks.mjs; do not edit by hand.
`
const out = join(here, '..', 'vendor', 'y-tiptap-nodemarks.js')
const text = header + s
if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n')
  if (current !== text) {
    console.error('vendor/y-tiptap-nodemarks.js is out of date; run this script without --check')
    process.exit(1)
  }
  console.log('vendor/y-tiptap-nodemarks.js is up to date')
} else {
  writeFileSync(out, text)
  console.log('wrote', out)
}
